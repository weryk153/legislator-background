// 經歷字串 → 分類。純函式，無 I/O，可單元測試。
//
// careers 的 title 是自由文字（立法院開放資料的「經歷」欄位原字串，見 scraper/adapters/ly.ts），
// 沒有結構化欄位可用，只能靠字串判斷。
//
// 判斷順序刻意是「先排除、再收錄」：「委員會」「協會」這些詞同時出現在公職與社會團體裡
// ——「客家委員會」「國家通訊傳播委員會」「修憲委員會」是機關，「新北市慢速壘球委員會」
// 是社團；「國會議員友好協會」是隨職務而來的院內組織，「員山鄉農會」是外部團體。
// 若不先認出機關與政黨，「委員會」一詞會把中央部會誤標成社會團體。
//
// **不對稱的容錯**：四類都會顯示在檔案頁上，沒有任何一筆被藏起來，所以落到「其他」
// 只是少了分組、資訊不減；但把中央部會誤標為「社會團體」是實質錯誤。因此凡是無法從
// 字面確認性質者一律保守歸「其他」，寧可漏標，不可錯標。
export type CareerCategory = 'public' | 'party' | 'social' | 'other';

// 政黨內部職務（黨團職務也算黨職，雖然掛在立法院底下）。
const PARTY = /中國國民黨|國民黨|民主進步黨|民進黨|台灣民眾黨|臺灣民眾黨|民眾黨|時代力量|台灣團結聯盟|臺灣團結聯盟|親民黨|新黨|無黨團結聯盟|無黨籍|黨部|黨團|中常委|中執委|中評委|黨主席|黨秘書長|黨代表/;
// 例外：帶黨名但實為公職的兩種寫法——
//   1. 屆別式：「台灣民眾黨第11屆立法委員」
//   2. 中選會選舉紀錄式：「111年直轄市議員（桃園市第02選舉區） 民主進步黨 當選」
//      民國年為 2-3 位數且在開頭，藉此與「民進黨2014年市長選舉對策委員會委員」這種
//      帶西元年的黨內職務區隔——後者年份 4 位數且不在開頭，仍歸黨職。
const ELECTED_OFFICE = '(立法委員|國大代表|議員|縣長|市長|鄉長|鎮長|村長|里長|市民代表|鄉民代表|代表)';
const PARTY_BUT_PUBLIC = new RegExp(
  `第[〇零一二三四五六七八九十百\\d、．.０-９]+屆[^，、]{0,8}${ELECTED_OFFICE}`
  + `|^\\d{2,3}年[^，、]{0,12}${ELECTED_OFFICE}`,
);

// 公家機關前綴。
const PUBLIC_ORG = /立法院|國民大會|監察院|考試院|司法院|行政院|總統府|國家安全會議|中央銀行|[縣市]議會|議會|[縣市]政府|省政府|鄉公所|鎮公所|區公所|市公所/;
// 民代與政務首長職稱（沒帶機關前綴也算公職）。
const PUBLIC_TITLE = /立法委員|國大代表|國民大會代表|[縣市]議員|省議員|省諮議員|鄉民代表|[縣市]長|鄉長|鎮長|村長|里長|部長|次長|署長|司長|處長|局長|政務委員|大使|代表處/;
const TERM = /第[〇零一二三四五六七八九十百\d、．.０-９]+屆|會期|選舉區/;
// 國會議員友好協會：隨立委職務而來的院內組織，卸任即失，屬公職而非外部社團。
const PARLIAMENT_BODY = /國會議員友好協會|國會議員協會|議員友好協會/;
// 中央二級機關的委員會、立法院常設與特種委員會，以及「機關前綴＋委員會」的一般形。
// 這些都以「委員會」結尾或含之，必須在社團判斷之前攔下來。
