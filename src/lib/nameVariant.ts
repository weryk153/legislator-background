/**
 * 姓名/搜尋用異體字正規化。
 *
 * 背景：officials.name 曾將「戴瑋姗」訂正為「戴瑋姍」（CEC 候選人名冊常見異體字），
 * 但使用者站內搜尋時常打原本的異體字，導致搜尋落空——這是資料修正後產生的鏡像問題。
 * 此工具將查詢字串與候選字串都正規化成同一種「標準寫法」，兩邊才能對上。
 *
 * 保守原則：僅收錄下列 4 組「確定屬於同一字的異體字」對照，且統一映射為單一標準寫法；
 * 刻意不擴大範圍，避免誤將兩個不同真實姓名用字合併視為相同（例如「陳」「陳」形近字絕不可混）。
 */
const CHAR_MAP: Record<string, string> = {
  // 姗 (U+59D7) → 姍 (U+59CD)：CEC 候選人名冊／官方訂正後皆用「姍」，但「姗」仍是使用者輸入常見寫法（如 戴瑋姍／戴瑋姗）。
  姗: '姍',
  // 台 (U+53F0) → 臺 (U+81FA)：教育部異體字字典之標準用字為「臺」，日常輸入/搜尋慣用簡化字「台」（如 台中／臺中）。
  台: '臺',
  // 峯 (U+5CEF) → 峰 (U+5CF0)：「峰」為現行標準寫法，「峯」為異體字，常見於人名（如 ○峯／○峰）。
  峯: '峰',
  // 恒 (U+6052) → 恆 (U+6046)：「恆」為標準字，「恒」為異體寫法，常見於人名/地名舊用字（如 ○恒／○恆）。
  恒: '恆',
};

// 間隔號常見異體：全形間隔號「・」、中點「·」、句點形式「．」、豎點「˙」、注音間隔號「･」
// 統一正規化為「‧」（U+2027，本站標籤分隔符號的標準寫法，如「國民黨‧立委」）。
const DOT_VARIANTS = /[・·．˙･]/g;

/**
 * 正規化姓名/查詢字串：去除首尾空白，將異體字統一為標準寫法，並統一間隔號變體。
 * 不做大小寫轉換（中文無此概念），僅處理上述 4 組異體字與間隔號變體。
 */
export function normalizeNameChars(s: string): string {
  const trimmed = s.trim();
  let out = '';
  for (const ch of trimmed) {
    out += CHAR_MAP[ch] ?? ch;
  }
  return out.replace(DOT_VARIANTS, '‧');
}
