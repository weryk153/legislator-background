import { describe, it, expect } from 'vitest';
import { parseCareerBlock } from '../scraper/lib/councilSiteParse';

import { splitByPerson } from '../scraper/lib/councilSiteParse';

describe('splitByPerson：一頁多人的議會頁按人拆開', () => {
  it('南投式：同一選區頁連續排列多位議員，以「姓名：」欄位為界', () => {
    const t = [
      '南投縣議會第20屆--議員', '姓名：', '林芳伃', '政黨：', '中國國民黨',
      '學歷：', '國立暨南國際大學碩士', '經歷：', '宏仁國中第一屆校友會理事長',
      '南投縣議會第20屆--議員', '姓名：', '蘇昱誠', '政黨：', '民主進步黨',
      '學歷：', '某某大學', '經歷：', '某某協會理事長',
    ].join('\n');
    const parts = splitByPerson(t);
    expect(parts.map(x => x.name)).toEqual(['林芳伃', '蘇昱誠']);
    expect(parts[0].text).toContain('宏仁國中第一屆校友會理事長');
    expect(parts[0].text).not.toContain('某某協會理事長');
  });

  it('沒有「姓名：」欄位時視為單人頁，整頁回傳', () => {
    const t = '陳偉杰\n政黨：中國國民黨\n經歷\n某某協會理事長';
    const parts = splitByPerson(t);
    expect(parts).toHaveLength(1);
    expect(parts[0].name).toBe('');
    expect(parts[0].text).toBe(t);
  });
});

describe('parseCareerBlock：從議會個人頁純文字抽經歷條列', () => {
  it('屏東式：「經歷：」後每行一筆', () => {
    const t = `梁育慈\n經歷：\n台灣大學政治學系\n高雄女中\n台北市議員梁文傑辦公室主任\n民進黨台北市黨部第18屆市代\n聯絡方式\n電話 08-1234567`;
    expect(parseCareerBlock(t)).toEqual([
      '台灣大學政治學系', '高雄女中', '台北市議員梁文傑辦公室主任', '民進黨台北市黨部第18屆市代',
    ]);
  });

  it('臺南式：「學歷」與「經歷」兩段，只取經歷', () => {
    const t = `學歷\n新營國小\n文化大學法律系財經組\n經歷\n北臺南家扶中心扶幼委員\n救國團南市指導委員\n政見\n一、推動…`;
    expect(parseCareerBlock(t)).toEqual(['北臺南家扶中心扶幼委員', '救國團南市指導委員']);
  });

  it('桃園式：阿拉伯數字編號', () => {
    const t = `經歷\n1. 桃園市議會第1、2屆議長\n2. 桃園縣中壢市丘（邱）姓宗親會理事長\n3. 桃園市機車商業同會公會顧問\n政見`;
    expect(parseCareerBlock(t)).toEqual([
      '桃園市議會第1、2屆議長', '桃園縣中壢市丘（邱）姓宗親會理事長', '桃園市機車商業同會公會顧問',
    ]);
  });

  it('彰化式：中文數字編號、句號結尾，且標題不叫「經歷」', () => {
    const t = `簡介\n五、台灣體育總會籃球協會會長。\n六、彰化縣警察局北斗分局警友會顧問。\n七、中華民國縣市體育會聯合總會常務監事。\n網站錯誤回報`;
    expect(parseCareerBlock(t)).toEqual([
      '台灣體育總會籃球協會會長', '彰化縣警察局北斗分局警友會顧問', '中華民國縣市體育會聯合總會常務監事',
    ]);
  });

  it('屏東式：標題是「學經歷：」四個字，同段混學歷與經歷', () => {
    const t = `出生：1989年\n政黨：民主進步黨\n學經歷：\n台灣大學政治學系\n台北市議員梁文傑辦公室主任\n民進黨台北市黨部第18屆市代\n本屆問政目標：\n一、監督…`;
    expect(parseCareerBlock(t)).toEqual([
      '台灣大學政治學系', '台北市議員梁文傑辦公室主任', '民進黨台北市黨部第18屆市代',
    ]);
  });

  it('彰化式：經歷沒有標題，直接是一串中文數字編號條列', () => {
    // 「簡介／政見／政績」只是分頁標籤，經歷緊接在基本欄位與學歷之後，沒有自己的標題。
    // 故除了標題錨點，也要能以「連續的編號條列」本身作為錨點。
    const t = [
      '第七選區 議員 謝典霖', '簡介', '政見', '政績', '性別：男', '電話：04-8894123',
      '現任：彰化縣議會第20屆議長', '國立中興大學國際政治研究所博士',
      '一、彰化縣議會第16、17、18、19屆議長。', '二、世界自由民主聯盟中華民國總會理事。',
      '三、中華民國籃球協會理事長。', '網站錯誤回報',
    ].join('\n');
    expect(parseCareerBlock(t)).toEqual([
      '彰化縣議會第16、17、18、19屆議長', '世界自由民主聯盟中華民國總會理事', '中華民國籃球協會理事長',
    ]);
  });

  it('左側選單的「議會簡介」不是內容標題，不可據此開始擷取', () => {
    const t = `公布欄\n議會沿革\n議會簡介\n議員資訊\n議案審查\n:::\n某某議員\n經歷\n某某體育會理事長\n網站錯誤回報`;
    expect(parseCareerBlock(t)).toEqual(['某某體育會理事長']);
  });

  it('新竹縣式：「學經歷」大標下再分「學 歷：」「經 歷：」子標題', () => {
    // 「學經歷」開段後緊接「學 歷：」，若該子標題被當成段落結束，整段經歷會被跳過，
    // 接著後面的「政見」段落反而被當成起點——抽到的會是政見不是經歷。
    const t = [
      '通訊地址：', '新竹縣竹北市光明六路8號',
      '學經歷', '學  歷：', '國立清華大學語言所碩士', '北一女中',
      '經  歷：', '新竹縣幸福城市推動協會榮譽理事長', '新竹縣姜呂邱謝宗親會顧問',
      '政見', '政  見：', '1、理性問政、仗義直言。',
    ].join('\n');
    expect(parseCareerBlock(t)).toEqual([
      '新竹縣幸福城市推動協會榮譽理事長', '新竹縣姜呂邱謝宗親會顧問',
    ]);
  });

  it('遇到頁尾導覽字樣就停止', () => {
    const t = `經歷\n某某協會理事長\n回上頁\n到上面\n網站導覽`;
    expect(parseCareerBlock(t)).toEqual(['某某協會理事長']);
  });

  it('新聞標題不是經歷——民國日期開頭者剔除', () => {
    // 高雄議長頁面在經歷之後接了新聞列表，且同一則新聞會出現在多位議員頁上，
    // 被當成經歷會把別人的活動記到本人頭上
    const t = [
      '經歷', '旗山天后宮副主任委員',
      '114/9/16高雄市塑膠製品商業同業公會拜會康議長 盼翻轉產業污名',
      '113/10/24大阪府日華友好交流協會到訪 康議長期待官方民間攜手深化台日情誼',
    ].join('\n');
    expect(parseCareerBlock(t)).toEqual(['旗山天后宮副主任委員']);
  });

  it('沒有可辨識的經歷段落時回空陣列', () => {
    expect(parseCareerBlock('姓名 選區 電話 傳真')).toEqual([]);
  });

  it('過短、過長與純數字的行不取', () => {
    const t = `經歷\n甲\n${'很長的職務名稱'.repeat(12)}\n2022\n正常的某某協會理事長`;
    expect(parseCareerBlock(t)).toEqual(['正常的某某協會理事長']);
  });
});
